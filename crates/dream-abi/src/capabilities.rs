//! Capability contracts are independent of the guest heap and `dream_platform` table.

use std::fmt::Write;

include!("capability_types.rs");

#[derive(Clone, Copy)]
enum Type {
    Void,
    U32,
    Size,
    Bytes,
    ConstBytes,
    Buffer,
}

impl Type {
    fn c(self) -> &'static str {
        match self {
            Self::Void => "void",
            Self::U32 => "uint32_t",
            Self::Size => "size_t",
            Self::Bytes => "uint8_t *",
            Self::ConstBytes => "const uint8_t *",
            Self::Buffer => "dream_host_buffer *",
        }
    }

    fn rust(self) -> &'static str {
        match self {
            Self::Void => "()",
            Self::U32 => "u32",
            Self::Size => "usize",
            Self::Bytes => "*mut u8",
            Self::ConstBytes => "*const u8",
            Self::Buffer => "*mut HostBuffer",
        }
    }
}

struct Operation {
    name: &'static str,
    alias: &'static str,
    params: &'static [(&'static str, Type)],
    result: Type,
}

const VERSION: u32 = 1;
const OPERATIONS: &[Operation] = &[
    Operation {
        name: "dream_capability_abi_version",
        alias: "AbiVersion",
        params: &[],
        result: Type::U32,
    },
    Operation {
        name: "dream_data_alloc",
        alias: "DataAlloc",
        params: &[("length", Type::Size)],
        result: Type::Bytes,
    },
    Operation {
        name: "dream_data_free",
        alias: "DataFree",
        params: &[("pointer", Type::Bytes), ("length", Type::Size)],
        result: Type::Void,
    },
    Operation {
        name: "dream_data_request",
        alias: "DataRequest",
        params: &[
            ("pointer", Type::ConstBytes),
            ("length", Type::Size),
            ("output", Type::Buffer),
        ],
        result: Type::Void,
    },
];

/// C declarations for the versioned capability boundary. Spans are borrowed for a call;
/// result buffers are owned by their producing capability and freed by that capability.
pub fn c_header() -> String {
    let mut out = String::from(
        "/* GENERATED by scripts/generate-capabilities.py. */\n#ifndef DREAM_CAPABILITIES_H\n#define DREAM_CAPABILITIES_H\n#include <stddef.h>\n#include <stdint.h>\n#ifdef __cplusplus\nextern \"C\" {\n#endif\n",
    );
    writeln!(out, "#define DREAM_CAPABILITY_ABI_VERSION {VERSION}").unwrap();
    out.push_str("/* Lengths count bytes. The caller supplies output storage; free results with dream_data_free. */\ntypedef struct dream_host_buffer { uint8_t *data; size_t length; } dream_host_buffer;\n");
    for operation in OPERATIONS {
        let params = operation
            .params
            .iter()
            .map(|(name, ty)| format!("{} {name}", ty.c()))
            .collect::<Vec<_>>()
            .join(", ");
        let params = if params.is_empty() { "void" } else { &params };
        writeln!(
            out,
            "{} {}({params});",
            operation.result.c(),
            operation.name
        )
        .unwrap();
    }
    out.push_str("#ifdef __cplusplus\n}\n#endif\n#endif\n");
    out
}

/// Rust C layouts and function types; implementations assign their exports to these aliases.
pub fn rust_types() -> String {
    let mut out = format!(
        "// GENERATED by scripts/generate-capabilities.py.\npub const CAPABILITY_ABI_VERSION: u32 = {VERSION};\n/// An owned capability result. Its allocator must release it using its original byte length.\n#[repr(C)]\npub struct HostBuffer {{\n    pub data: *mut u8,\n    pub length: usize,\n}}\n"
    );
    for operation in OPERATIONS {
        let params = operation
            .params
            .iter()
            .map(|(_, ty)| ty.rust())
            .collect::<Vec<_>>()
            .join(", ");
        let result = match operation.result {
            Type::Void => String::new(),
            ty => format!(" -> {}", ty.rust()),
        };
        writeln!(
            out,
            "pub type {} = unsafe extern \"C\" fn({params}){result};",
            operation.alias
        )
        .unwrap();
    }
    out
}

/// A wasm32 adapter for the same scalar/span contract as the native C declarations.
pub fn javascript() -> String {
    let mut out = format!(
        "// GENERATED by scripts/generate-capabilities.py.\nexport const CAPABILITY_ABI_VERSION = {VERSION};\nexport function bindDataCodecs(exports) {{\n"
    );
    for operation in OPERATIONS {
        writeln!(out, "  if (typeof exports.{} !== \"function\") throw new Error(\"missing capability export: {}\");", operation.name, operation.name).unwrap();
    }
    out.push_str(r#"  if (exports.dream_capability_abi_version() !== CAPABILITY_ABI_VERSION) throw new Error("data capability ABI version mismatch");
  if (!(exports.memory instanceof WebAssembly.Memory)) throw new Error("data capability has no linear memory");
  return input => {
    // The output descriptor is two wasm32 words: pointer and byte length.
    const descriptor = exports.dream_data_alloc(8);
    if (!descriptor) throw new Error("data capability descriptor allocation failed");
    let pointer = 0;
    let output = 0;
    let length = 0;
    const checked = (pointer, length) => {
      const size = exports.memory.buffer.byteLength;
      if (pointer > size || length > size - pointer) throw new Error("capability buffer is out of bounds");
      return new Uint8Array(exports.memory.buffer, pointer, length);
    };
    try {
      pointer = exports.dream_data_alloc(input.length);
      if (!pointer && input.length) throw new Error("data capability input allocation failed");
      checked(pointer >>> 0, input.length).set(input);
      exports.dream_data_request(pointer, input.length, descriptor);
      checked(descriptor >>> 0, 8);
      const view = new DataView(exports.memory.buffer);
      output = view.getUint32(descriptor >>> 0, true);
      length = view.getUint32((descriptor >>> 0) + 4, true);
      return checked(output, length).slice();
    } finally {
      if (output) exports.dream_data_free(output, length);
      if (pointer) exports.dream_data_free(pointer, input.length);
      exports.dream_data_free(descriptor, 8);
    }
  };
}
"#);
    out
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn generated_contracts_are_current() {
        assert_eq!(
            rust_types(),
            include_str!("capability_types.rs").replace("\r\n", "\n")
        );
        assert_eq!(
            c_header(),
            include_str!("../../dream-mir/src/runtime/c/include/dream_capabilities.h")
                .replace("\r\n", "\n")
        );
        assert_eq!(
            javascript(),
            include_str!("../../../runtime/src/capabilities.js").replace("\r\n", "\n")
        );
    }
}
