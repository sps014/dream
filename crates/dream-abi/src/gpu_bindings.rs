//! Compact shader binding IDs shared by the generator and native/browser bundle readers.
use std::fmt::Write;

pub const GPU_BUNDLE_ABI_VERSION: u32 = 1;

pub struct BindingLayout {
    pub name: &'static str,
    pub kind: u32,
    pub descriptor: &'static str,
}

/// IDs are one-based; zero means the target uses a recorded native layout.
pub const BINDING_LAYOUTS: &[BindingLayout] = &[
    BindingLayout {
        name: "Uniform",
        kind: 6,
        descriptor: r#"{"buffer":{"type":"uniform"}}"#,
    },
    BindingLayout {
        name: "ReadOnlyStorage",
        kind: 1,
        descriptor: r#"{"buffer":{"type":"read-only-storage"}}"#,
    },
    BindingLayout {
        name: "Storage",
        kind: 1,
        descriptor: r#"{"buffer":{"type":"storage"}}"#,
    },
    BindingLayout {
        name: "FilteringSampler",
        kind: 3,
        descriptor: r#"{"sampler":{"type":"filtering"}}"#,
    },
    BindingLayout {
        name: "Texture2DFloat",
        kind: 2,
        descriptor: r#"{"texture":{"sampleType":"float","viewDimension":"2d","multisampled":false}}"#,
    },
    BindingLayout {
        name: "StorageR32Float",
        kind: 4,
        descriptor: r#"{"storageTexture":{"format":"r32float","access":"read-write","viewDimension":"2d"}}"#,
    },
    BindingLayout {
        name: "StorageRg32Float",
        kind: 4,
        descriptor: r#"{"storageTexture":{"format":"rg32float","access":"read-write","viewDimension":"2d"}}"#,
    },
    BindingLayout {
        name: "StorageRgba32Float",
        kind: 4,
        descriptor: r#"{"storageTexture":{"format":"rgba32float","access":"read-write","viewDimension":"2d"}}"#,
    },
    BindingLayout {
        name: "StorageR32Uint",
        kind: 4,
        descriptor: r#"{"storageTexture":{"format":"r32uint","access":"read-write","viewDimension":"2d"}}"#,
    },
];

pub fn binding_layout(id: u32) -> Option<&'static BindingLayout> {
    BINDING_LAYOUTS.get(id.checked_sub(1)? as usize)
}

pub fn artifacts() -> Vec<(&'static str, String)> {
    let mut c = String::from(
        "/* GENERATED by scripts/generate-capabilities.py. */\n#ifndef DREAM_GPU_BINDINGS_H\n#define DREAM_GPU_BINDINGS_H\n#include <stdint.h>\n#define DREAM_GPU_LAYOUT_NONE UINT32_C(0)\n",
    );
    let mut dream = String::from(
        "module system.gpu.shaders;\n\n// GENERATED by scripts/generate-capabilities.py. IDs are the DGPB binding contract.\ninternal enum WebGpuBindingLayout {\n    None = 0,\n",
    );
    let mut js = String::from(
        "// GENERATED by scripts/generate-capabilities.py.\nexport const GPU_BINDING_LAYOUTS = [null,\n",
    );
    let mut json = String::from("[\n");
    for (index, layout) in BINDING_LAYOUTS.iter().enumerate() {
        let id = index + 1;
        writeln!(
            c,
            "#define DREAM_GPU_LAYOUT_{} UINT32_C({id})",
            layout.name.to_ascii_uppercase()
        )
        .unwrap();
        writeln!(dream, "    {} = {id},", layout.name).unwrap();
        writeln!(js, "  [{}, {}],", layout.kind, layout.descriptor).unwrap();
        if index > 0 {
            json.push_str(",\n");
        }
        write!(
            json,
            "  {{\"id\":{id},\"name\":\"{}\",\"kind\":{},\"descriptor\":{}}}",
            layout.name, layout.kind, layout.descriptor
        )
        .unwrap();
    }
    writeln!(
        c,
        "#define DREAM_GPU_BUNDLE_ABI_VERSION UINT32_C({GPU_BUNDLE_ABI_VERSION})"
    )
    .unwrap();
    c.push_str("static inline uint32_t dream_gpu_binding_kind(uint32_t id) {\n    switch (id) {\n");
    for (index, layout) in BINDING_LAYOUTS.iter().enumerate() {
        writeln!(c, "        case {}: return {};", index + 1, layout.kind).unwrap();
    }
    c.push_str("        default: return 0;\n    }\n}\n#endif\n");
    dream.push_str("}\n");
    js.push_str("];\n");
    writeln!(
        js,
        "export const GPU_BUNDLE_ABI_VERSION = {GPU_BUNDLE_ABI_VERSION};"
    )
    .unwrap();
    json.push_str("\n]\n");
    vec![
        (
            "crates/dream-mir/src/runtime/c/include/dream_gpu_bindings.h",
            c,
        ),
        (
            "crates/dream-stdlib/src/system/gpu/shaders/web_gpu_binding_layout.dream",
            dream,
        ),
        ("runtime/src/hosts/gpu_layouts.js", js),
        ("crates/dream-abi/gpu_binding_layouts.json", json),
    ]
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn generated_gpu_bindings_are_current() {
        let root = std::path::Path::new(env!("CARGO_MANIFEST_DIR")).join("../..");
        for (path, expected) in artifacts() {
            let actual = std::fs::read_to_string(root.join(path)).unwrap();
            assert_eq!(actual.replace("\r\n", "\n"), expected, "{path}");
        }
        assert!(binding_layout(0).is_none());
        assert!(binding_layout(u32::MAX).is_none());
    }
}
