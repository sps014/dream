//! One C-compatible contract for opaque guest references and asynchronous lifetimes.

use std::fmt::Write;

const VERSION: u32 = 1;
const STATUSES: &[(&str, &str, u32)] = &[
    ("OK", "Ok", 0),
    ("INVALID", "Invalid", 1),
    ("VERSION", "Version", 2),
    ("BOUNDS", "Bounds", 3),
    ("CANCELLED", "Cancelled", 4),
    ("UNSUPPORTED", "Unsupported", 5),
    ("CLOSED", "Closed", 6),
    ("FAILED", "Failed", 7),
];

pub const EXPORTS: &[(&str, &str)] = &[
    ("__dream_guest_version", "dream_guest_abi_version"),
    ("__dream_guest_data", "dream_guest_data"),
    ("__dream_guest_length", "dream_guest_length"),
    ("__dream_guest_string", "dream_string_alloc"),
    ("__dream_guest_array", "dream_array_new"),
];

// Types are named here so both generated tables have exactly the same field order and widths.
const CALLBACKS: &[(&str, &str, &str)] = &[
    (
        "string_alloc",
        "void *(*string_alloc)(int32_t)",
        "unsafe extern \"C\" fn(i32) -> *mut u8",
    ),
    (
        "array_new",
        "void *(*array_new)(int32_t, int32_t)",
        "unsafe extern \"C\" fn(i32, i32) -> *mut u8",
    ),
    (
        "data",
        "void *(*data)(void *, uint32_t)",
        "unsafe extern \"C\" fn(*mut u8, u32) -> *mut u8",
    ),
    (
        "length",
        "uint32_t (*length)(void *)",
        "unsafe extern \"C\" fn(*mut u8) -> u32",
    ),
    (
        "truncate",
        "uint32_t (*truncate)(void *, uint32_t)",
        "unsafe extern \"C\" fn(*mut u8, u32) -> u32",
    ),
    (
        "complete",
        "void (*complete)(void *, uint64_t)",
        "unsafe extern \"C\" fn(*mut u8, u64)",
    ),
    (
        "status",
        "int32_t (*status)(void *)",
        "unsafe extern \"C\" fn(*mut u8) -> i32",
    ),
    (
        "retain",
        "void (*retain)(void *)",
        "unsafe extern \"C\" fn(*mut u8)",
    ),
    (
        "release",
        "void (*release)(void *)",
        "unsafe extern \"C\" fn(*mut u8)",
    ),
];

pub fn c_header() -> String {
    let mut out = format!(
        "/* GENERATED by scripts/generate-capabilities.py. */\n#ifndef DREAM_GUEST_CONTRACT_H\n#define DREAM_GUEST_CONTRACT_H\n#include <stdint.h>\n#define DREAM_GUEST_ABI_VERSION {VERSION}\n/* References are opaque. Data is borrowed until the call returns; async hosts copy inputs.\n * String spans contain UTF-16 code units; array spans contain length elements.\n * Allocations transfer one reference to the caller. Completion transfers its owned result.\n * Retain/release pin references while a foreign operation may still access them. */\nenum {{ DREAM_GUEST_ARRAY = 0, DREAM_GUEST_STRING = 1 }};\nenum {{ DREAM_FUTURE_PENDING = 0, DREAM_FUTURE_READY = 1, DREAM_FUTURE_CANCELLED = 2 }};\ntypedef struct dream_guest_context {{\n    uint32_t version;\n    uint32_t size;\n"
    );
    for (_, c, _) in CALLBACKS {
        writeln!(out, "    {c};").unwrap();
    }
    out.push_str("} dream_guest_context;\n#endif\n");
    let mut statuses = String::from("typedef enum dream_host_status {\n");
    for (name, _, value) in STATUSES {
        writeln!(statuses, "    DREAM_HOST_{name} = {value},").unwrap();
    }
    statuses.push_str("} dream_host_status;\n");
    out = out.replace(
        "typedef struct dream_guest_context",
        &format!("{statuses}typedef struct dream_guest_context"),
    );
    out
}

pub fn rust_types() -> String {
    let mut out = format!(
        "// GENERATED by scripts/generate-capabilities.py.\npub const GUEST_ABI_VERSION: u32 = {VERSION};\npub const GUEST_ARRAY: u32 = 0;\npub const GUEST_STRING: u32 = 1;\npub const FUTURE_PENDING: i32 = 0;\npub const FUTURE_READY: i32 = 1;\npub const FUTURE_CANCELLED: i32 = 2;\n/// A copied callback table; its functions remain valid for the guest's lifetime.\n#[repr(C)]\n#[derive(Clone, Copy)]\npub struct GuestContext {{\n    pub version: u32,\n    pub size: u32,\n"
    );
    for (name, _, rust) in CALLBACKS {
        writeln!(out, "    pub {name}: Option<{rust}>,").unwrap();
    }
    out.push_str("}\n");
    out.push_str("/// Transport failures are independent of capability-specific error details.\n#[repr(u32)]\n#[derive(Clone, Copy, Debug, PartialEq, Eq)]\npub enum HostStatus {\n");
    for (_, name, value) in STATUSES {
        writeln!(out, "    {name} = {value},").unwrap();
    }
    out.push_str("}\n");
    out
}

pub fn javascript() -> String {
    let mut out = format!(
        "// GENERATED by scripts/generate-capabilities.py.\nexport const GUEST_ABI_VERSION = {VERSION};\nexport const HOST_STATUS = {{\n"
    );
    for (name, _, value) in STATUSES {
        writeln!(out, "  {name}: {value},").unwrap();
    }
    out.push_str("};\n");
    out
}

include!("guest_types.rs");

#[cfg(test)]
mod tests {
    #[test]
    fn generated_contract_is_current() {
        assert_eq!(
            super::rust_types(),
            include_str!("guest_types.rs").replace("\r\n", "\n")
        );
        assert_eq!(
            super::c_header(),
            include_str!("../../dream-mir/src/runtime/c/include/dream_guest_contract.h")
                .replace("\r\n", "\n")
        );
    }
}
