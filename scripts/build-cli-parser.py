#!/usr/bin/env python3
"""Build the shared clap WebAssembly adapter; --check verifies its source fingerprint."""
import argparse
import base64
import hashlib
import json
from pathlib import Path
import re
import subprocess
import tomllib

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / "runtime/src/hosts/cli_parser.js"


def build_inputs():
    """Only what the wasm build consumes, so unrelated workspace dependency edits stay fresh."""
    tree = subprocess.check_output(
        ["cargo", "--color", "never", "tree", "-p", "dream-host-cli", "--target", "wasm32-unknown-unknown", "-e", "normal,build",
         "--prefix", "none", "--locked", "-f", "{p}"], cwd=ROOT, text=True)
    # Local paths differ per checkout; registry names and versions identify the resolved graph.
    packages = sorted({re.sub(r" \(.*\)$", "", line.strip()) for line in tree.splitlines() if line.strip()})
    manifest = tomllib.loads((ROOT / "Cargo.toml").read_text())
    profiles = manifest.get("profile", {})
    settings = {
        "edition": manifest["workspace"]["package"]["edition"],
        "release": profiles.get("release", {}),
        "cli-wasm": profiles.get("cli-wasm", {}),
    }
    return packages, json.dumps(settings, sort_keys=True)


def fingerprint():
    packages, settings = build_inputs()
    digest = hashlib.sha256()
    digest.update("\n".join(packages).encode())
    digest.update(b"\0")
    digest.update(settings.encode())
    for path in [*sorted((ROOT / "crates/dream-host-cli").rglob("*.rs")), ROOT / "crates/dream-host-cli/Cargo.toml"]:
        digest.update(path.relative_to(ROOT).as_posix().encode())
        digest.update(b"\0")
        digest.update(path.read_bytes())
    return digest.hexdigest()


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    stamp = "// Source SHA-256: " + fingerprint()
    if args.check:
        if not OUTPUT.exists() or stamp not in OUTPUT.read_text():
            raise SystemExit("CLI parser adapter is stale; run python scripts/build-cli-parser.py")
        print("CLI parser adapter matches its Rust sources and dependency lock.")
        return
    subprocess.run(["cargo", "build", "-p", "dream-host-cli", "--target", "wasm32-unknown-unknown", "--profile", "cli-wasm", "--locked"], cwd=ROOT, check=True)
    binary = ROOT / "target/wasm32-unknown-unknown/cli-wasm/dream_host_cli.wasm"
    compiler = subprocess.check_output(["rustc", "--version"], text=True).strip()
    data = base64.b64encode(binary.read_bytes()).decode()
    OUTPUT.write_text("// Generated by scripts/build-cli-parser.py; " + compiler + "\n" + stamp + '\nexport const cliParserBase64 = "' + data + '";\n')
    print(f"Embedded {binary.stat().st_size} bytes of shared clap parser.")


if __name__ == "__main__":
    main()
