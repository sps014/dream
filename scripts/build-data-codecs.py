#!/usr/bin/env python3
"""Build the shared data-format WebAssembly adapter; --check verifies its source fingerprint."""
import argparse
import base64
import hashlib
from pathlib import Path
import subprocess

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / "runtime/src/hosts/data_codecs.js"


def fingerprint():
    sources = [ROOT / "Cargo.lock", ROOT / "Cargo.toml", *sorted((ROOT / "crates/dream-host-data").rglob("*.rs")),
               ROOT / "crates/dream-host-data/Cargo.toml"]
    digest = hashlib.sha256()
    for path in sources:
        digest.update(path.relative_to(ROOT).as_posix().encode())
        digest.update(b"\0")
        digest.update(path.read_bytes())
    return digest.hexdigest()


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    stamp = "// Source SHA-256: " + fingerprint()
    if args.check:
        if not OUTPUT.exists() or stamp not in OUTPUT.read_text():
            raise SystemExit("Data codec adapter is stale; run python scripts/build-data-codecs.py")
        print("Data codec adapter matches its Rust sources and dependency lock.")
        return
    subprocess.run(["cargo", "build", "-p", "dream-host-data", "--target", "wasm32-unknown-unknown", "--profile", "cli-wasm", "--locked"], cwd=ROOT, check=True)
    binary = ROOT / "target/wasm32-unknown-unknown/cli-wasm/dream_host_data.wasm"
    compiler = subprocess.check_output(["rustc", "--version"], text=True).strip()
    data = base64.b64encode(binary.read_bytes()).decode()
    OUTPUT.write_text("// Generated by scripts/build-data-codecs.py; " + compiler + "\n" + stamp + '\nexport const dataCodecsBase64 = "' + data + '";\n')
    print(f"Embedded {binary.stat().st_size} bytes of shared data codecs.")


if __name__ == "__main__":
    main()
