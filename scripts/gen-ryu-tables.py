#!/usr/bin/env python3
"""Generates the power-of-five tables used by `ShortestDecimal` (Ryu, Adams 2018).

    python scripts/gen-ryu-tables.py          # rewrite the generated file
    python scripts/gen-ryu-tables.py --check  # fail if it is stale

Each entry is a 125-bit approximation stored as two `ulong` words, low word first.
"""

import argparse
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
OUTPUT = ROOT / "crates" / "dream-stdlib" / "src" / "system" / "core" / "shortest_decimal_tables.dream"
BITS = 125
INV_TABLE_SIZE = 342
TABLE_SIZE = 326
MASK = (1 << 64) - 1


def table(name, entries):
    words = []
    for value in entries:
        words += [value & MASK, value >> 64]
    lines = []
    for i in range(0, len(words), 4):
        lines.append("    " + " ".join(f"0x{w:016X}uL," for w in words[i:i + 4]))
    lines[-1] = lines[-1].rstrip(",")
    return f"\ninternal let {name}: ulong[] = [\n" + "\n".join(lines) + "\n];\n"


def render():
    inverse = []
    for i in range(INV_TABLE_SIZE):
        power = 5 ** i
        inverse.append((1 << (power.bit_length() - 1 + BITS)) // power + 1)
    direct = []
    for i in range(TABLE_SIZE):
        power = 5 ** i
        shift = power.bit_length() - BITS
        direct.append(power >> shift if shift >= 0 else power << -shift)
    return (
        "// Generated by scripts/gen-ryu-tables.py; do not edit.\n"
        "module system.core;\n"
        "\n"
        "// floor(2^(bitlength(5^i) - 1 + 125) / 5^i) + 1 for i in 0..342.\n"
        + table("RYU_POW5_INV_SPLIT", inverse).lstrip("\n")
        + "\n// 5^i scaled to exactly 125 significant bits for i in 0..326.\n"
        + table("RYU_POW5_SPLIT", direct).lstrip("\n")
    )


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    text = render()
    stale = not OUTPUT.exists() or OUTPUT.read_text(encoding="utf-8") != text
    if args.check:
        if stale:
            print(f"stale: {OUTPUT.relative_to(ROOT)}")
        return 1 if stale else 0
    if stale:
        OUTPUT.write_text(text, encoding="utf-8", newline="\n")
        print(f"wrote {OUTPUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
