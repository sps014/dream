#!/usr/bin/env python3
"""Generates the `system.text` Unicode tables and conformance vectors from the Unicode Character Database.

    python scripts/gen-unicode-tables.py          # rewrite the generated files
    python scripts/gen-unicode-tables.py --check  # fail if they are stale

Downloads the pinned UCD release into `target/ucd/<version>/` on first use.
"""

import argparse
import pathlib
import sys
import urllib.request

UCD_VERSION = "16.0.0"
ROOT = pathlib.Path(__file__).resolve().parent.parent
CACHE = ROOT / "target" / "ucd" / UCD_VERSION
TEXT = ROOT / "crates" / "dream-stdlib" / "src" / "system" / "text"
TESTS = ROOT / "tests" / "projects" / "text"
SOURCES = {
    "UnicodeData.txt": "ucd/UnicodeData.txt",
    "SpecialCasing.txt": "ucd/SpecialCasing.txt",
    "DerivedCoreProperties.txt": "ucd/DerivedCoreProperties.txt",
    "DerivedNormalizationProps.txt": "ucd/DerivedNormalizationProps.txt",
    "GraphemeBreakProperty.txt": "ucd/auxiliary/GraphemeBreakProperty.txt",
    "emoji-data.txt": "ucd/emoji/emoji-data.txt",
    "NormalizationTest.txt": "ucd/NormalizationTest.txt",
    "GraphemeBreakTest.txt": "ucd/auxiliary/GraphemeBreakTest.txt",
}
HEADER = (
    "// Generated by scripts/gen-unicode-tables.py from Unicode {version}; do not edit.\n"
    "module system.text;\n"
)
# Grapheme_Cluster_Break values, in the order `GraphemeBreaker` expects.
GCB = ["Other", "CR", "LF", "Control", "Extend", "ZWJ", "Regional_Indicator", "Prepend",
       "SpacingMark", "L", "V", "T", "LV", "LVT"]
INCB = {"None": 0, "Consonant": 1, "Extend": 2, "Linker": 3}
SBASE, SCOUNT = 0xAC00, 11172


def ucd(name):
    path = CACHE / name
    if not path.exists():
        CACHE.mkdir(parents=True, exist_ok=True)
        url = f"https://www.unicode.org/Public/{UCD_VERSION}/{SOURCES[name]}"
        path.write_bytes(urllib.request.urlopen(url, timeout=60).read())
    return path.read_text(encoding="utf-8")


def records(name):
    for line in ucd(name).splitlines():
        line = line.split("#", 1)[0].strip()
        if line:
            yield [field.strip() for field in line.split(";")]


def code_range(field):
    lo, _, hi = field.partition("..")
    return int(lo, 16), int(hi or lo, 16)


def property_set(name, wanted, value_index=1):
    out = set()
    for fields in records(name):
        if fields[value_index] == wanted:
            lo, hi = code_range(fields[0])
            out.update(range(lo, hi + 1))
    return out


def unicode_data():
    rows = {}
    pending = None
    for fields in records("UnicodeData.txt"):
        cp = int(fields[0], 16)
        if fields[1].endswith(", First>"):
            pending = cp
            continue
        if fields[1].endswith(", Last>"):
            for c in range(pending, cp + 1):
                rows[c] = fields
            continue
        rows[cp] = fields
    return rows


def ranges(cps):
    out = []
    for cp in sorted(cps):
        if out and out[-1][1] == cp - 1:
            out[-1][1] = cp
        else:
            out.append([cp, cp])
    return out


def runs(value_of, limit=0x110000):
    """Starts and values of maximal runs of equal `value_of(cp)`, covering the whole code space."""
    starts, values = [], []
    prev = None
    for cp in range(limit):
        v = value_of(cp)
        if v != prev:
            starts.append(cp)
            values.append(v)
            prev = v
    return starts, values


def table(name, kind, values, suffix=""):
    body = []
    line = "   "
    for v in values:
        item = f" {v}{suffix},"
        if len(line) + len(item) > 100:
            body.append(line)
            line = "   "
        line += item
    if line.strip():
        body.append(line)
    return f"\ninternal let {name}: {kind}[] = [\n" + "\n".join(body) + "\n];\n"


def case_tables(rows):
    special = {}
    for fields in records("SpecialCasing.txt"):
        if len(fields) > 4 and fields[4]:
            continue
        cp = int(fields[0], 16)
        special[cp] = {
            "lower": [int(x, 16) for x in fields[1].split()],
            "upper": [int(x, 16) for x in fields[3].split()],
        }
    out = HEADER.format(version=UCD_VERSION)
    for direction, column in (("lower", 13), ("upper", 12)):
        keys, values, extra = [], [], []
        for cp in sorted(rows):
            mapped = special.get(cp, {}).get(direction)
            if mapped is None:
                simple = rows[cp][column]
                mapped = [int(simple, 16)] if simple else [cp]
            if mapped == [cp]:
                continue
            keys.append(cp)
            if len(mapped) == 1:
                values.append(mapped[0])
            else:
                # Multi-scalar mappings live in the extra table, flagged above the code space.
                values.append(0x200000 + len(extra))
                extra.append(len(mapped))
                extra.extend(mapped)
        prefix = f"UNICODE_{direction.upper()}"
        out += table(f"{prefix}_KEYS", "int", keys)
        out += table(f"{prefix}_VALUES", "int", values)
        out += table(f"{prefix}_EXTRA", "int", extra or [0])
    for name, prop in (("CASED", "Cased"), ("CASE_IGNORABLE", "Case_Ignorable")):
        flat = [v for r in ranges(property_set("DerivedCoreProperties.txt", prop)) for v in r]
        out += table(f"UNICODE_{name}_RANGES", "int", flat)
    return out


def decompositions(rows):
    raw = {}
    for cp, fields in rows.items():
        field = fields[5]
        if not field:
            continue
        compat = field.startswith("<")
        parts = field.split()[1:] if compat else field.split()
        raw[cp] = (compat, [int(p, 16) for p in parts])

    def full(cp, allow_compat):
        if SBASE <= cp < SBASE + SCOUNT:
            return [cp]
        entry = raw.get(cp)
        if entry is None or (entry[0] and not allow_compat):
            return [cp]
        return [c for part in entry[1] for c in full(part, allow_compat)]

    canon = {cp: full(cp, False) for cp in raw if full(cp, False) != [cp]}
    compat = {cp: full(cp, True) for cp in raw if full(cp, True) != canon.get(cp, [cp])}
    return raw, canon, compat


def normalization_tables(rows):
    raw, canon, compat = decompositions(rows)
    ccc = {cp: int(f[3]) for cp, f in rows.items() if int(f[3])}
    excluded = property_set("DerivedNormalizationProps.txt", "Full_Composition_Exclusion")
    pairs = sorted(
        ((v[1][0] << 21) | v[1][1], cp)
        for cp, v in raw.items()
        if not v[0] and len(v[1]) == 2 and cp not in excluded
    )
    out = HEADER.format(version=UCD_VERSION)
    starts, values = runs(lambda cp: ccc.get(cp, 0))
    out += table("UNICODE_CCC_STARTS", "int", starts)
    out += table("UNICODE_CCC_VALUES", "int", values)
    for name, mapping in (("CANONICAL", canon), ("COMPAT", compat)):
        keys, info, data = [], [], []
        for cp in sorted(mapping):
            keys.append(cp)
            info.append((len(data) << 5) | len(mapping[cp]))
            data.extend(mapping[cp])
        out += table(f"UNICODE_{name}_KEYS", "int", keys)
        out += table(f"UNICODE_{name}_INFO", "int", info)
        out += table(f"UNICODE_{name}_DATA", "int", data)
    out += table("UNICODE_COMPOSE_KEYS", "long", [k for k, _ in pairs], "L")
    out += table("UNICODE_COMPOSE_VALUES", "int", [v for _, v in pairs])
    return out


def grapheme_tables():
    gcb = {}
    for fields in records("GraphemeBreakProperty.txt"):
        lo, hi = code_range(fields[0])
        for cp in range(lo, hi + 1):
            gcb[cp] = GCB.index(fields[1])
    pict = property_set("emoji-data.txt", "Extended_Pictographic")
    incb = {}
    for fields in records("DerivedCoreProperties.txt"):
        if fields[1] == "InCB":
            lo, hi = code_range(fields[0])
            for cp in range(lo, hi + 1):
                incb[cp] = INCB[fields[2]]
    starts, values = runs(
        lambda cp: gcb.get(cp, 0) | (16 if cp in pict else 0) | (incb.get(cp, 0) << 5)
    )
    out = HEADER.format(version=UCD_VERSION)
    out += table("UNICODE_GRAPHEME_STARTS", "int", starts)
    out += table("UNICODE_GRAPHEME_VALUES", "int", values)
    return out


def dream_cps(cps):
    return "[" + ", ".join(str(c) for c in cps) + "]"


def conformance_tests():
    norm = []
    for i, fields in enumerate(records("NormalizationTest.txt")):
        if fields[0].startswith("@"):
            continue
        if i % 7:
            continue
        cols = [[int(x, 16) for x in f.split()] for f in fields[:5]]
        norm.append(cols)
    graphemes = []
    for line in ucd("GraphemeBreakTest.txt").splitlines():
        line = line.split("#", 1)[0].strip()
        if not line:
            continue
        tokens = line.split()
        cps, breaks = [], []
        for t in tokens:
            if t == "÷":
                breaks.append(len(cps))
            elif t != "×":
                cps.append(int(t, 16))
        graphemes.append((cps, breaks))
    out = [
        "// Generated by scripts/gen-unicode-tables.py from the Unicode "
        f"{UCD_VERSION} conformance files; do not edit.",
        "import system.testing;",
        "import system.text;",
        "",
        "fun from_cps(cps: int[]): string {",
        "    let out = StringBuilder();",
        "    for (let cp in cps) {",
        "        if cp >= 65536 {",
        "            out.append_char((char)(55296 + ((cp - 65536) >> 10)));",
        "            out.append_char((char)(56320 + ((cp - 65536) & 1023)));",
        "        } else {",
        "            out.append_char((char)cp);",
        "        }",
        "    }",
        "    return out.build();",
        "}",
        "",
        "fun check_normalization(cols: int[][]): void {",
        "    let source = from_cps(cols[0]);",
        "    Assert.eq(source.normalize(UnicodeNormForm.Nfc), from_cps(cols[1]));",
        "    Assert.eq(source.normalize(UnicodeNormForm.Nfd), from_cps(cols[2]));",
        "    Assert.eq(source.normalize(UnicodeNormForm.Nfkc), from_cps(cols[3]));",
        "    Assert.eq(source.normalize(UnicodeNormForm.Nfkd), from_cps(cols[4]));",
        "}",
        "",
        "fun check_graphemes(cps: int[], breaks: int[]): void {",
        "    let clusters = from_cps(cps).graphemes();",
        "    Assert.eq(clusters.length, breaks.length - 1);",
        "    let i = 0;",
        "    while i < clusters.length {",
        "        let expected = Array.alloc<int>(breaks[i + 1] - breaks[i]);",
        "        let j = 0;",
        "        while j < expected.length {",
        "            expected[j] = cps[breaks[i] + j];",
        "            j = j + 1;",
        "        }",
        "        Assert.eq(clusters[i], from_cps(expected));",
        "        i = i + 1;",
        "    }",
        "}",
    ]
    chunk = 200
    for n in range(0, len(norm), chunk):
        out += ["", "@test", f"fun unicode_normalization_{n // chunk}(): void {{"]
        for cols in norm[n:n + chunk]:
            out.append(f"    check_normalization([{', '.join(dream_cps(c) for c in cols)}]);")
        out.append("}")
    for n in range(0, len(graphemes), chunk):
        out += ["", "@test", f"fun unicode_graphemes_{n // chunk}(): void {{"]
        for cps, breaks in graphemes[n:n + chunk]:
            out.append(f"    check_graphemes({dream_cps(cps)}, {dream_cps(breaks)});")
        out.append("}")
    return "\n".join(out) + "\n"


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    rows = unicode_data()
    outputs = {
        TEXT / "unicode_case_data.dream": case_tables(rows),
        TEXT / "unicode_normalization_data.dream": normalization_tables(rows),
        TEXT / "grapheme_data.dream": grapheme_tables(),
        TESTS / "unicode_conformance.dream": conformance_tests(),
    }
    stale = [p for p, text in outputs.items() if not p.exists() or p.read_text(encoding="utf-8") != text]
    if args.check:
        for p in stale:
            print(f"stale: {p.relative_to(ROOT)}")
        return 1 if stale else 0
    for p in stale:
        p.write_text(outputs[p], encoding="utf-8", newline="\n")
        print(f"wrote {p.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
